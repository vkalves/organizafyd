// Decode/re-encode only picture and first audio stream. Do not copy original
// container tags, track tags, chapters, thumbnails, data or subtitle streams.
export const videoCleanCommand = (input: string, output: string) => [
  "-i",
  input,
  "-map",
  "0:v:0",
  "-map",
  "0:a:0?",
  "-map_metadata",
  "-1",
  "-map_metadata:s",
  "-1",
  "-map_chapters",
  "-1",
  "-vf",
  "pad=ceil(iw/2)*2:ceil(ih/2)*2,sidedata=delete",
  "-c:v",
  "libx264",
  "-preset",
  "veryfast",
  "-crf",
  "20",
  "-pix_fmt",
  "yuv420p",
  "-bsf:v",
  "filter_units=remove_types=6",
  "-af",
  "asidedata=delete",
  "-c:a",
  "aac",
  "-b:a",
  "128k",
  "-fflags",
  "+bitexact",
  "-flags:v",
  "+bitexact",
  "-flags:a",
  "+bitexact",
  "-metadata",
  "encoder=",
  "-metadata:s:v",
  "encoder=",
  "-metadata:s:a",
  "encoder=",
  "-movflags",
  "+faststart",
  "-y",
  output,
];
