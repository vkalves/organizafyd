import { act, cleanup, renderHook } from "@testing-library/react";
import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import { afterEach, expect, it, vi } from "vitest";
import type { ReactNode } from "react";
const request = vi.hoisted(() => vi.fn());
vi.mock("./api", () => ({ publisherRequest: request }));
import { fetchAnalyticsReport, useInstagramAnalytics } from "./useInstagramAnalytics";
afterEach(() => { cleanup(); vi.useRealTimers(); vi.resetAllMocks(); });
const page = (views: number, cursor?: string) => ({ checked_at: "2026-11-12", accounts: [{ account_id: "a", unavailable: false, complete: !cursor, nextCursor: cursor, videos: [{ id: "r", account_id: "a", media_product_type: "REELS", views, likes: 3 }] }] });
it("collects pagination without double-counting and preserves partial pages when Meta fails", async () => {
  request.mockResolvedValueOnce(page(10, "next")).mockResolvedValueOnce(page(20));
  expect((await fetchAnalyticsReport(true)).accounts[0]).toMatchObject({ complete: true, videos: [{ id: "r", views: 20 }] });
  expect(request).toHaveBeenLastCalledWith("analytics", { account_id: "a", after: "next" });
  request.mockResolvedValueOnce(page(10, "next")).mockRejectedValueOnce(new Error("Meta offline"));
  expect((await fetchAnalyticsReport(true)).accounts[0]).toMatchObject({ complete: false, nextCursor: "next", videos: [{ views: 10 }] });
});
it("refreshes dashboard metrics on the interval and stops when the dashboard is disabled", async () => {
  vi.useFakeTimers({ toFake: ["setInterval", "clearInterval", "Date"] });
  const client = new QueryClient({ defaultOptions: { queries: { retry: false, gcTime: 0 } } });
  request.mockResolvedValue(page(10));
  const wrapper = ({ children }: { children: ReactNode }) => <QueryClientProvider client={client}>{children}</QueryClientProvider>;
  const hook = renderHook(({ enabled }) => useInstagramAnalytics("owner", enabled, 60_000), { wrapper, initialProps: { enabled: true } });
  await act(async () => { await new Promise(resolve => setTimeout(resolve, 10)); });
  expect(hook.result.current.report.isSuccess).toBe(true);
  request.mockResolvedValue(page(50));
  await act(async () => { await vi.advanceTimersByTimeAsync(60_000); });
  expect(request).toHaveBeenCalledTimes(2);
  expect(client.getQueryData(["ig-analytics", "owner"])).toMatchObject({ accounts: [{ videos: [{ views: 50 }] }] });
  hook.rerender({ enabled: false });
  await act(async () => { await vi.advanceTimersByTimeAsync(120_000); });
  expect(request).toHaveBeenCalledTimes(2);
  hook.unmount(); client.clear();
});
